"""Write the wire enums the app uses as one Dart file.

Source: contract-audit/enums.json (exported from the backend's OpenAPI document).
Output: lib/core/models/wire_enums.dart

Each enum has `fromJson` (an unknown value gives null and is logged, never a
real value) and `toJson` (the wire value).

Run from the app root:

    python3 tool/gen_enums.py          # write the file
    python3 tool/gen_enums.py --check  # exit 1 when the file is out of date
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

APP = Path(__file__).resolve().parents[1]
ENUMS = APP.parents[2] / "contract-audit" / "enums.json"
OUT = APP / "lib" / "core" / "models" / "wire_enums.dart"

# Enums the app reads or sends. Add a name here when the app starts using one.
USED = [
    "AIJobStatus",
    "AIJobType",
    "HotspotType",
    "StorageFolderType",
    "TourStatus",
    "TourVisibility",
    "UploadStatus",
]

DART_RESERVED = {
    "abstract", "as", "assert", "async", "await", "break", "case", "catch",
    "class", "const", "continue", "default", "do", "else", "enum", "extends",
    "false", "final", "finally", "for", "if", "in", "is", "new", "null",
    "on", "rethrow", "return", "super", "switch", "this", "throw", "true",
    "try", "var", "void", "while", "with", "yield",
}


def member(wire: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", wire)
    name = parts[0].lower() + "".join(p[:1].upper() + p[1:].lower() for p in parts[1:])
    if not name or name[0].isdigit() or name in DART_RESERVED:
        name = f"v{name[:1].upper()}{name[1:]}" if name else "empty"
    return name


def render(enums: dict[str, list[str]]) -> str:
    out = [
        "// GENERATED by tool/gen_enums.py from contract-audit/enums.json.",
        "// Do not edit by hand. Run `python3 tool/gen_enums.py` after the backend enums change.",
        "//",
        "// `fromJson` maps an unknown wire value to null and logs it. It never falls back",
        "// to a real value. `toJson` returns the wire value.",
        "",
        "import 'package:flutter/foundation.dart';",
        "",
    ]
    for name in USED:
        values = enums[name]
        members = [member(v) for v in values]
        if len(set(members)) != len(members):
            raise SystemExit(f"{name}: two wire values give the same Dart name")
        out.append(f"enum {name} {{")
        for i, (m, v) in enumerate(zip(members, values)):
            end = ";" if i == len(values) - 1 else ","
            out.append(f"  {m}('{v}'){end}")
        out += [
            "",
            f"  const {name}(this.wire);",
            "",
            "  final String wire;",
            "",
            f"  static final Map<String, {name}> _byWire = {{",
            f"    for (final v in {name}.values) v.wire: v,",
            "  };",
            "",
            f"  /// Null for null and for a value the app does not know (logged).",
            f"  static {name}? fromJson(Object? value) {{",
            "    if (value == null) return null;",
            "    final match = _byWire[value];",
            "    if (match == null) {",
            f"      debugPrint('{name}: unknown wire value $value');",
            "    }",
            "    return match;",
            "  }",
            "",
            "  String toJson() => wire;",
            "}",
            "",
        ]
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    enums = json.loads(ENUMS.read_text())
    text = render(enums)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is out of date. Run python3 tool/gen_enums.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(APP)} ({len(USED)} enums)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
